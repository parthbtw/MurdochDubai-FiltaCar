import { fileURLToPath } from 'node:url'
import type { Page } from '@playwright/test'
import { test, expect } from './fixtures'

// One worker runs these in source order against one disposable data copy.
// Each journey owns different seed parts; uploads create their own records.
async function openPart(page: Page, id: string, lane: 'Ready' | 'Missing' | 'Specialist' = 'Ready') {
  await page.goto('/')
  await page.getByRole('tab', { name: new RegExp(`^${lane} `) }).click()
  await page.getByRole('link', { name: `Review ${id}`, exact: true }).click()
  await expect(page.getByRole('heading', { name: id, exact: true, level: 1 })).toBeVisible()
}

async function approve(page: Page) {
  const action = page.getByRole('region', { name: 'Listing approval', exact: true })
  await action.getByRole('button', { name: 'Approve listing', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Approve this listing draft?', exact: true })
  await expect(confirmation).toContainText('You confirm the facts and the wording. FiltaCar does not publish anything.')
  await confirmation.getByRole('button', { name: 'Approve', exact: true }).click()
  await expect(confirmation).toBeHidden()
  await expect(action).toContainText('Approved by the seller')
}

test('01 Normal: source evidence, seller approval and mock CSV export', async ({ page, localGet }) => {
  await page.goto('/')
  await expect(page.getByRole('tab', { name: 'Ready 3', exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Missing 5', exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Specialist 2', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Review MIR-0001', exact: true }).click()
  await page.getByRole('button', { name: /^Source for part number:/ }).click()
  const source = page.getByRole('dialog', { name: 'Where this came from', exact: true })
  await expect(source.getByText('spreadsheet row 3', { exact: true })).toBeVisible()
  await source.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(source).toBeHidden()
  await approve(page)
  await page.getByRole('navigation', { name: 'Main tabs' }).getByRole('link', { name: 'Export', exact: true }).click()
  const included = page.getByRole('region', { name: 'Included parts', exact: true })
  await expect(included.getByRole('link', { name: /^MIR-0001/ })).toBeVisible()
  const csv = page.getByRole('link', { name: 'Download mock eBay CSV', exact: true })
  await expect(csv).toHaveAttribute('href', '/api/export/ebay.csv')
  const href = await csv.getAttribute('href')
  if (!href) throw new Error('The mock CSV link has no href')
  const response = await localGet(href)
  expect(response.ok()).toBe(true)
  const text = await response.text()
  expect(text).toContain('MOCK, NOT PUBLISHED')
  expect(text).toContain('MIR-0001')
})

