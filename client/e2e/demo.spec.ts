test('07 Individual seller: upload a label, confirm 2016 and find the new part', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Who is selling\?/ }).click()
  const seller = page.getByRole('dialog', { name: 'Who is selling?', exact: true })
  await seller.getByRole('radio', { name: /^Individual: IND-DXB-001/ }).click()
  await expect(seller).toBeHidden()
  const tabs = page.getByRole('navigation', { name: 'Main tabs' })
  await tabs.getByRole('link', { name: 'Sell a part', exact: true }).click()
  await page.getByLabel('Choose from library file', { exact: true }).setInputFiles(fileURLToPath(new URL('../../data/demo/clear_label.png', import.meta.url)))
  await page.getByRole('button', { name: 'Upload', exact: true }).click()
  await page.getByRole('link', { name: 'This matches my label', exact: true }).click()
  const id = new URL(page.url()).pathname.split('/')[2]
  expect(id).toMatch(/^MIR-\d+$/)
  const required = page.getByRole('region', { name: 'Required question', exact: true })
  const count = required.getByText(/^\d+ required questions? left$/)
  await expect(required.getByRole('textbox', { name: 'Donor year', exact: true })).toBeVisible()
  const before = Number((await count.innerText()).match(/^\d+/)?.[0])
  expect(before).toBeGreaterThan(1)
  await required.getByRole('textbox', { name: 'Donor year', exact: true }).fill('2016')
  await required.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(count).toHaveText(`${before - 1} required ${before - 1 === 1 ? 'question' : 'questions'} left`)
  await expect(page.getByRole('status', { name: 'Saved change', exact: true })).toContainText('Donor year saved. 1 required question resolved.')
  await page.reload()
  await expect(count).toHaveText(`${before - 1} required ${before - 1 === 1 ? 'question' : 'questions'} left`)
  await tabs.getByRole('link', { name: 'My parts', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'My parts', exact: true, level: 1 })).toBeVisible()
  const card = page.getByRole('listitem').filter({ has: page.getByRole('img', { name: `Recorded photo for ${id}`, exact: true }) })
  await expect(card).toBeVisible()
  await expect(card.getByRole('link')).toHaveAttribute('href', `/sell/${id}/questions`)
  await expect(card).not.toContainText('clear_label.png')
})

