test('04 Refused approval: MIR-0009 and MIR-0010 retain reasons and number conflict', async ({ page }) => {
  for (const id of ['MIR-0009', 'MIR-0010']) {
    await openPart(page, id, 'Specialist')
    const action = page.getByRole('region', { name: 'Listing approval', exact: true })
    const button = action.getByRole('button', { name: 'Approve listing', exact: true })
    await expect(button).toBeDisabled()
    await expect(button).toHaveAttribute('aria-describedby', 'approval-reasons-sticky')
    await action.locator('summary').click()
    await expect(action.getByText('Specialist review required.', { exact: true })).toBeVisible()
    await expect(action).toContainText('electrical function cannot be verified', { ignoreCase: true })
    if (id === 'MIR-0010') {
      const conflict = page.getByRole('button', { name: /^Source for part number:/ })
      await expect(conflict).toContainText('Conflict')
      await expect(conflict).toContainText('SBM-7946-PF')
      await expect(conflict).toContainText('SBM-7946-PX')
    }
  }
})

test('05 Claim guard: MIR-0003 strikes subjective Arabic and keeps a factual title', async ({ page }) => {
  await openPart(page, 'MIR-0003')
  const draft = page.getByRole('region', { name: 'Listing draft', exact: true })
  await draft.locator('summary').click()
  const blocked = draft.getByRole('listitem').filter({ hasText: 'بحالة ممتازة' })
  await expect(blocked.getByRole('deletion')).toHaveText('بحالة ممتازة')
  await expect(blocked).toContainText('Cannot claim: subjective condition; describe the actual condition instead')
  const title = draft.getByRole('heading', { name: 'Title', exact: true }).locator('+ p')
  await expect(title).toContainText('SBM-7942-PR18')
  await expect(title).not.toContainText(/\b(?:genuine|authentic|original|guaranteed|fits|working|excellent|perfect|mint|like new|good condition)\b|حالة جيدة|حالة ممتازة|ممتاز|نظيف|زي الجديد|مثل الجديد/i)
})

